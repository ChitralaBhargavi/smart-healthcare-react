import mongoose from 'mongoose'

const doctorSetupTokenSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      unique: true,
    },
    tokenHash: {
      type: String,
      required: true,
      unique: true,
    },
    expiresAt: {
      type: Date,
      required: true,
      index: { expires: 0 },
    },
    usedAt: {
      type: Date,
    },
  },
  { timestamps: true },
)

export default mongoose.model('DoctorSetupToken', doctorSetupTokenSchema)
